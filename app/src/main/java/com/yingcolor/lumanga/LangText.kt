package com.yingcolor.lumanga

import java.util.Locale

/**
 * Interface language. [SYSTEM] is not a language of its own: it follows the phone's setting and
 * falls back to English for anything this app does not speak.
 *
 * [tag] is what gets stored in preferences, so it must stay stable. [label] is written in the
 * language itself, the way language pickers do it, and is never translated.
 */
enum class Lang(val tag: String, val label: String) {
    SYSTEM("", "跟随系统"),
    ZH("zh-CN", "简体中文"),
    ZH_TW("zh-TW", "繁體中文"),
    EN("en", "English"),
    JA("ja", "日本語"),
    KO("ko", "한국어"),
    RU("ru", "Русский");

    companion object {
        fun fromTag(tag: String): Lang = entries.firstOrNull { it.tag == tag } ?: SYSTEM
    }

    /** What to show in the picker: [label] except for "follow system", which is translated. */
    fun displayName(): String = if (this == SYSTEM) S.languageSystem else label
}

/**
 * The language to actually draw with. Chinese is split by script rather than by country: a
 * zh-Hant phone is offered 繁體中文 wherever it is, and everything else Chinese gets 简体.
 */
fun systemLang(locale: Locale = Locale.getDefault()): Lang {
    val tag = locale.toLanguageTag().lowercase()
    val language = locale.language.lowercase()
    val traditional = tag.contains("hant") || tag.endsWith("-tw") || tag.endsWith("-hk") ||
        tag.endsWith("-mo")
    return when {
        language == "zh" -> if (traditional) Lang.ZH_TW else Lang.ZH
        language == "ja" -> Lang.JA
        language == "ko" -> Lang.KO
        language == "ru" -> Lang.RU
        language == "en" -> Lang.EN
        else -> Lang.EN
    }
}

/** The text table for a language. [Lang.SYSTEM] is resolved by the caller. */
internal fun tableOf(lang: Lang): Texts = when (lang) {
    Lang.SYSTEM, Lang.ZH -> ZH
    Lang.ZH_TW -> ZH_TW
    Lang.EN -> EN
    Lang.JA -> JA
    Lang.KO -> KO
    Lang.RU -> RU
}

